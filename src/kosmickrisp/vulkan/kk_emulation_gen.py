"""Generate capability filtering and its reference table from one registry."""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'vulkan' / 'util'))
from vk_physical_device_features_gen import get_feature_structs_from_xml, get_renamed_feature
from vk_physical_device_properties_gen import get_property_structs_from_xml


def documentation(entries):
    lines = ['.. Generated by kk_emulation_gen.py from kk_emulation.json.', '',
             '.. list-table::', '   :header-rows: 1', '   :widths: 10 20 24 8 12 14 12', '',
             '   * - Name', '     - Emulated behavior', '     - Cost',
             '     - Performance default', '     - Performance reason',
             '     - When off', '     - Enable']
    for row in entries:
        controls = row['extensions'] + row['features'] + row['properties']
        controls += list(row.get('property_bits', {}))
        if row.get('format_feature'):
            controls.append(row['format_feature'])
        lines += ['   * - ``' + row['name'] + '``',
                  '     - ' + row['description'],
                  '       Controls: ' + ', '.join('``' + s + '``' for s in controls) + '.',
                  '     - ' + row['cost_class'] + '. ' + row['cost_note'],
                  '     - ' + ('On' if row['performance'] else 'Off'),
                  '     - ' + row['performance_reason'],
                  '     - ' + row['off_consequence'],
                  '     - ``performance,+' + row['name'] + '``']
    return '\n'.join(lines) + '\n'


def generate(entries, xml, beta):
    _, feature_structs, _ = get_feature_structs_from_xml([xml], beta)
    _, property_structs, _ = get_property_structs_from_xml([xml], 'true' if beta else 'false')
    fields = defaultdict(set)
    for struct in feature_structs:
        for extension in struct.reqs.extensions:
            fields[extension.name].update(get_renamed_feature(struct.c_type, f)
                                          for f in struct.features)
    # Legacy extensions without feature structs gained booleans on promotion.
    fields['VK_EXT_sampler_filter_minmax'].add('samplerFilterMinmax')
    fields['VK_KHR_sampler_mirror_clamp_to_edge'].add('samplerMirrorClampToEdge')
    fields['VK_EXT_descriptor_indexing'].add('descriptorIndexing')
    fields['VK_EXT_shader_viewport_index_layer'].update(['shaderOutputViewportIndex', 'shaderOutputLayer'])
    fields['VK_KHR_draw_indirect_count'].add('drawIndirectCount')

    doc = ET.parse(xml)
    aliases = {t.get('name'): t.get('alias') for t in doc.findall('./types/type') if t.get('alias')}
    props_by_type = {p.c_type: p for p in property_structs}
    props = defaultdict(set)
    for extension in doc.findall('./extensions/extension'):
        for t in extension.findall('./require/type'):
            name = t.get('name')
            while name in aliases:
                name = aliases[name]
            struct = props_by_type.get(name)
            if struct:
                props[extension.get('name')].update(p.actual_name for p in struct.properties)

    out = ['/* SPDX-License-Identifier: MIT */',
           '/* Generated from kk_emulation.json and the Vulkan registry. */',
           '#define KK_EMULATION_COUNT ' + str(len(entries)),
           'static const char *const kk_emulation_names[] = {']
    for row in entries:
        if not re.fullmatch('[a-z][a-z0-9_]*', row['name']):
            raise ValueError('Invalid entry name')
        out.append('   "' + row['name'] + '",')
    if len({row['name'] for row in entries}) != len(entries):
        raise ValueError('Duplicate entry name')
    out += ['};', 'static const bool kk_emulation_performance[] = {']
    out += ['   ' + ('true' if row['performance'] else 'false') + ',' for row in entries]
    out += ['};', 'static void',
            'kk_emulation_disable(unsigned index, struct vk_device_extension_table *extensions,',
            '                     struct vk_features *features, struct vk_properties *properties)',
            '{', '   switch (index) {']
    for i, row in enumerate(entries):
        out.append('   case ' + str(i) + ':')
        for extension in row['extensions']:
            out.append('      extensions->' + extension[3:] + ' = false;')
        for feature in row['features']:
            out.append('      features->' + feature + ' = false;')
        for prop in row['properties']:
            out.append('      memset(&properties->' + prop + ', 0, sizeof(properties->' + prop + '));')
        for prop, bits in row.get('property_bits', {}).items():
            out.append('      properties->' + prop + ' &= ~(' + bits + ');')
        out.append('      break;')
    out += ['   }', '}', 'static void',
            'kk_emulation_hide_extension(const char *name, struct vk_features *features,',
            '                            struct vk_properties *properties)', '{']
    for extension in sorted(set(fields) | set(props)):
        out.append('   if (strcmp(name, "' + extension + '") == 0) {')
        for feature in sorted(fields[extension]):
            out.append('      features->' + feature + ' = false;')
        for prop in sorted(props[extension]):
            out.append('      memset(&properties->' + prop + ', 0, sizeof(properties->' + prop + '));')
        out += ['      return;', '   }']
    out += ['}']
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--registry', required=True)
    parser.add_argument('--xml')
    parser.add_argument('--beta', default='false', choices=['true', 'false'])
    parser.add_argument('--out')
    parser.add_argument('--docs')
    parser.add_argument('--check-docs', action='store_true')
    args = parser.parse_args()
    entries = json.loads(Path(args.registry).read_text())
    for row in entries:
        if not isinstance(row.get('performance'), bool):
            parser.error(row['name'] + ': performance must be a boolean')
        for field in ['performance_reason', 'off_consequence']:
            value = row.get(field)
            if not isinstance(value, str) or not value.strip() or '\n' in value or '\r' in value:
                parser.error(row['name'] + ': ' + field + ' must be one nonempty line')
    if args.docs:
        text = documentation(entries)
        if args.check_docs:
            if Path(args.docs).read_text() != text:
                parser.error('Generated emulation reference differs from the registry')
        else:
            Path(args.docs).write_text(text)
    if args.out:
        if not args.xml:
            parser.error('--out requires --xml')
        Path(args.out).write_text(generate(entries, args.xml, args.beta == 'true'))


if __name__ == '__main__':
    main()
